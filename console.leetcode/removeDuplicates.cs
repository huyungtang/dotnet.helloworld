  public partial class Solution
  {

    #region Properties ####################################################################################################################



    #endregion ############################################################################################################################

    #region Public Functions ##############################################################################################################

    public int RemoveDuplicates(int[] nums)
    {
      if (nums.Length == 0)
      {
        return 0;
      }

      int cnt = 1;

      for (int i = 1; i < nums.Length; i++)
      {
        if (nums[cnt - 1] != nums[i])
        {
          nums[cnt] = nums[i];
          cnt++;
        }
      }

      return cnt;
    }

    #endregion ############################################################################################################################

    #region Private Functions #############################################################################################################



    #endregion ############################################################################################################################

  }
}