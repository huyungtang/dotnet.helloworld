    #region Public Functions ##############################################################################################################

    public string LongestCommonPrefix(string[] strs)
    {
      var len = strs.Length;
      switch (len)
      {
        case 0:
          return "";
        case 1:
          return strs[0];
        default:
          var prefix = strs[0];

          for (var i = 1; i < len; i++)
          {
            while (!strs[i].StartsWith(prefix) && prefix != "")
            {
              prefix = prefix[..^1];
            }

            if (prefix == "")
            {
              break;
            }
          }

          return prefix;
      }
    }

    #endregion ############################################################################################################################

