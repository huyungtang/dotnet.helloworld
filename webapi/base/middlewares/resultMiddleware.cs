namespace webapi.middlewares
{
  public static class ResultMiddlewareExtension
  {
    #region Properties ####################################################################################################################



    #endregion ############################################################################################################################

    #region Public Functions ##############################################################################################################

    public static void UseResult(this IApplicationBuilder builder)
    {
      builder.UseMiddleware<ResultMiddleware>();
    }

    #endregion ############################################################################################################################

    #region Private Functions #############################################################################################################



    #endregion ############################################################################################################################

  }

  public class ResultMiddleware(RequestDelegate next)
  {

    #region Properties ####################################################################################################################

    private readonly RequestDelegate _next = next;

    #endregion ############################################################################################################################

    #region Public Functions ##############################################################################################################

    public async Task InvokeAsync(HttpContext context)
    {
      await _next(context);

      // TODO: formatted return
    }

    #endregion ############################################################################################################################

    #region Private Functions #############################################################################################################



    #endregion ############################################################################################################################

  }
}