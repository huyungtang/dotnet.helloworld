namespace webapi.middlewares
{
  public static class IdentityMiddlewareExtension
  {

    #region Properties ####################################################################################################################



    #endregion ############################################################################################################################

    #region Public Functions ##############################################################################################################

    public static void UseIdentity(this IApplicationBuilder builder)
    {
      builder.UseMiddleware<IdentityMiddleware>();
    }

    #endregion ############################################################################################################################

    #region Private Functions #############################################################################################################



    #endregion ############################################################################################################################

  }

  public class IdentityMiddleware(RequestDelegate next)
  {

    #region Properties ####################################################################################################################

    private readonly RequestDelegate _next = next;

    #endregion ############################################################################################################################

    #region Public Functions ##############################################################################################################

    public async Task InvokeAsync(HttpContext context)
    {
      //TODO: need to implement - get user information
      // var _scoped = context.RequestServices.GetService<IContextService>()!;

      await _next(context);
    }

    #endregion ############################################################################################################################

    #region Private Functions #############################################################################################################



    #endregion ############################################################################################################################

  }
