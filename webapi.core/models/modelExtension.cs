namespace webapi.core
{
  public static class ModelExtension
  {

    #region Properties ####################################################################################################################



    #endregion ############################################################################################################################

    #region Public Functions ##############################################################################################################

    public static bool IsA<T>(this object obj, Action<T?>? action)
      where T : class
    {
      if (obj is T)
      {
        action?.Invoke(obj as T);

        return true;
      }

      return false;
    }

    #endregion ############################################################################################################################

    #region Private Functions #############################################################################################################



    #endregion ############################################################################################################################

  }
}